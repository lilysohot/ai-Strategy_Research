const { chromium } = require('../web/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')

;(async () => {
  fs.mkdirSync('.scratch/blog-preview', { recursive: true })
  const browser = await chromium.launch({ headless: true })
  const errors = []
  try {
    for (const mobile of [false, true]) {
      const context = await browser.newContext({ viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 }, hasTouch: mobile })
      const page = await context.newPage()
      page.on('pageerror', err => errors.push(err.message))
      const label = mobile ? 'mobile' : 'desktop'
      await page.goto('http://127.0.0.1:55183/blog')
      await page.getByRole('heading', { name: /慢慢想/ }).waitFor()
      assert.equal(await page.locator('.post-row').count(), 6)
      assert.equal(await page.title(), '白切粥 · 慢慢想，好好写')
      await page.screenshot({ path: `.scratch/blog-preview/${label}-home.png`, fullPage: true })
      await page.getByRole('button', { name: '技术', exact: true }).click()
      assert.equal(await page.locator('.post-row').count(), 2)
      assert.ok((await page.locator('.post-row').allTextContents()).every(text => text.includes('技术')))
      await page.getByRole('searchbox', { name: '搜索文章' }).fill('笔记')
      assert.equal(await page.locator('.post-row').count(), 1)
      await page.getByRole('searchbox', { name: '搜索文章' }).fill('没有匹配结果')
      await page.getByRole('heading', { name: '这个念头，还没有写下。' }).waitFor()
      await page.getByRole('button', { name: '查看全部文章' }).click()
      assert.equal(await page.locator('.post-row').count(), 6)
      await page.locator('.post-row').first().click()
      await page.waitForURL('**/blog/leave-space-for-curiosity')
      await page.getByRole('heading', { name: '给好奇心，留一点空白', exact: true }).waitFor()
      assert.ok(page.url().endsWith('/blog/leave-space-for-curiosity'))
      assert.equal(await page.locator('.article-body section').count(), 3)
      await page.getByRole('button', { name: '当前字号 18，点击切换正文字号' }).click()
      assert.equal(await page.locator('.article-body').evaluate(el => getComputedStyle(el).fontSize), '20px')
      await page.getByRole('button', { name: '复制链接' }).click()
      await page.waitForFunction(() => document.querySelector('.copy-status')?.textContent.length > 0)
      await page.locator('.article-toc a').nth(1).click()
      assert.ok(page.url().endsWith('#section-1'))
      await page.waitForFunction(() => parseFloat(document.querySelector('.reading-progress').style.width) > 0)
      await page.screenshot({ path: `.scratch/blog-preview/${label}-article.png`, fullPage: true })
      await page.reload()
      await page.getByRole('heading', { name: '给好奇心，留一点空白', exact: true }).waitFor()
      await page.locator('.next-article').click()
      await page.getByRole('heading', { name: '从一个小工具开始，重新理解创造', exact: true }).waitFor()
      await page.getByRole('link', { name: '返回文章列表' }).click()
      await page.locator('.post-list').waitFor()
      await page.getByRole('navigation').getByRole('link', { name: '归档' }).click()
      await page.waitForFunction(() => Math.abs(document.querySelector('#archive').getBoundingClientRect().top - 36) < 5)
      assert.equal(await page.locator('.archive-month a').count(), 6)
      await page.getByRole('navigation').getByRole('link', { name: '关于' }).click()
      await page.getByRole('heading', { name: '你好，我是白切粥。' }).waitFor()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
      await page.goto('http://127.0.0.1:55183/blog/missing')
      await page.getByRole('heading', { name: '这一页，还没有写下。' }).waitFor()
      await page.getByRole('link', { name: '返回博客首页' }).click()
      await page.getByRole('heading', { name: /慢慢想/ }).waitFor()
      await context.close()
      console.log(`PASS ${label}: home, filtering, search, article, typography, copy feedback, contents, progress, reload, next article, archive, about, 404, layout`)
    }
    const page = await browser.newPage({ reducedMotion: 'reduce', viewport: { width: 320, height: 720 } })
    await page.goto('http://127.0.0.1:55183/blog')
    await page.getByRole('heading', { name: /慢慢想/ }).waitFor()
    assert.equal(await page.locator('.orbit-ring').first().evaluate(el => getComputedStyle(el).animationName), 'none')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.keyboard.press('Tab')
    assert.equal(await page.locator(':focus').innerText(), '跳到正文')
    await page.keyboard.press('Enter')
    assert.equal(await page.locator(':focus').getAttribute('id'), 'blog-content')
    assert.deepEqual(errors, [])
    console.log('PASS reduced motion, 320px layout, keyboard skip link, zero browser exceptions')
  } finally { await browser.close() }
})().catch(err => { console.error(err); process.exitCode = 1 })
