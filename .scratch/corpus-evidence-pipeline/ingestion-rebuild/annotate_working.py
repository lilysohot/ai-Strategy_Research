def exact(text, quote):
    positions = [i for i, ch in enumerate(text) if not ch.isspace()]
    needle = re.sub(r'\s+', '', quote)
    haystack = ''.join(text[i] for i in positions)
    start = haystack.find(needle)
    assert start >= 0, quote
    return text[positions[start]:positions[start + len(needle) - 1] + 1]

def item(key, quote, text, kind='value', unit=None, period=None, row=None, col=None):
    return dict(kind=kind, unit=unit, period=period, row=row, col=col,
                cell=f'{row} × {col}' if kind == 'table_cell' else None,
                quote=exact(slots[key]['full_text'], quote), text=text)

