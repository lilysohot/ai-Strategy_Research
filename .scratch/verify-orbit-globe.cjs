const { chromium } = require('../web/node_modules/playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')

;(async () => {
  const browser = await chromium.launch({ headless: true })
  fs.mkdirSync('.scratch/orbit-globe', { recursive: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/api/auth/registration-status', route => route.fulfill({ json: { enabled: false } }))
    await page.goto('http://127.0.0.1:55183/login')
    const canvas = page.locator('.globe-surface')
    await canvas.waitFor()
    await page.waitForTimeout(150)
    const snapshot = () => canvas.evaluate(el => el.toDataURL())
    const first = await snapshot()
    await page.waitForTimeout(900)
    assert.notEqual(await snapshot(), first, 'sphere surface must rotate independently of outer rings')
    await page.screenshot({ path: '.scratch/orbit-globe/login.png' })
    await page.locator('.orbit-core').screenshot({ path: '.scratch/orbit-globe/globe.png' })
    await page.getByTestId('enter-login').click()
    await page.getByTestId('username').waitFor()
    await page.waitForFunction(() => document.activeElement?.getAttribute('autocomplete') === 'username')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.waitForTimeout(150)
    const still = await snapshot()
    await page.waitForTimeout(350)
    assert.equal(await snapshot(), still, 'reduced motion stops the sphere')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.waitForTimeout(350)
    assert.notEqual(await snapshot(), still, 'restoring motion resumes the sphere')
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: '返回首页' }).click()
    await page.waitForTimeout(500)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.goto('http://127.0.0.1:55183/blog')
    await canvas.waitFor()
    await page.waitForTimeout(250)
    const blogFrame = await snapshot()
    await page.waitForTimeout(350)
    assert.notEqual(await snapshot(), blogFrame)
    await page.locator('#archive').scrollIntoViewIfNeeded()
    await page.waitForTimeout(200)
    const offscreenFrame = await snapshot()
    await page.waitForTimeout(350)
    assert.equal(await snapshot(), offscreenFrame, 'offscreen sphere stops rendering')
    await page.goto('http://127.0.0.1:55183/blog/leave-space-for-curiosity')
    await page.locator('#article-title').waitFor()
    assert.equal(await canvas.count(), 0)
    assert.deepEqual(errors, [])
    console.log('PASS: animated 3D surface, login reveal/focus, reduced motion pause/resume, mobile layout, shared blog globe, offscreen pause, unmount without errors')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
